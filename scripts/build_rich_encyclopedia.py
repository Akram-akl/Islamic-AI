def strip_tashkeel(text):
    if not text:
        return ""
    return re.sub(r'[\u064B-\u065F\u0670]', '', text)

def normalize_text(text):
    if not text:
        return ""
    text = strip_tashkeel(text)
    text = re.sub(r'[إأآا]', 'ا', text)
    text = text.replace('ة', 'ه').replace('ى', 'ي')
    return re.sub(r'[^\w\s]', '', text)

