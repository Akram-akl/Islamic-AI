def classify_query(question: str) -> str:
    """
    يُعيد:
    - "islamic_research"  → يُجيب من قاعدة البيانات حصراً
    - "islamic_advisory"  → يُجيب AI بنفسه (مع إضافة آيات اختيارياً)
    - "general"           → يُجيب كأي AI عادي
    """
    q = question.strip().lower()

    # 1. محادثة عامة
    for kw in GENERAL_CHAT_KEYWORDS:
        if kw in q:
            return "general"

    # 2. سؤال بحثي إسلامي (يحتاج نص من DB)
    research_score = sum(1 for kw in ISLAMIC_RESEARCH_KEYWORDS if kw in q)
    if research_score >= 1:
        return "islamic_research"

    # 3. استشاري إسلامي (AI يُجيب بنفسه)
    advisory_score = sum(1 for kw in ISLAMIC_ADVISORY_KEYWORDS if kw in q)
    if advisory_score >= 1:
        return "islamic_advisory"

    # 4. هل يحتوي على أسماء سور أو أرقام آيات؟
    if re.search(r'(سورة|surah)\s+\w+', q):
        return "islamic_research"
    if re.search(r'\d+\s*[:؛]\s*\d+', q):  # مثل 2:255
        return "islamic_research"

    # 5. افتراضي: عام
    return "general"


