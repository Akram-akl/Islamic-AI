async def prefill():
    from core.search_engine import search_quran, search_hadiths, search_books
    from core.ai_service import generate_answer, save_to_answer_cache

    print(f"🔄 جار ملء الكاش بـ {len(COMMON_QUESTIONS)} سؤال شائع...")
    print("هذا يعني أن المستخدمين سيحصلون على إجابات فورية بدون AI\n")

    success = 0
    failed = 0

    for i, question in enumerate(COMMON_QUESTIONS, 1):
        try:
            print(f"[{i}/{len(COMMON_QUESTIONS)}] {question[:50]}...", end=" ")

            # بحث في المصادر
            books   = search_books(question, limit=3)
            hadiths = search_hadiths(question, None, 5)
            quran   = search_quran(question, "hafs", 3)
            sources = books + hadiths + quran

            # توليد الإجابة
            result  = await generate_answer(question, sources)
            answer  = result.get("answer", "")

            if answer and len(answer) > 30 and result.get("provider") != "error-fallback":
                save_to_answer_cache(question, answer)
                print(f"✅ [{result['provider']}]")
                success += 1
            else:
                print(f"⚠️ قصيرة جداً")
                failed += 1

            # انتظار قصير لعدم تحميل API
            await asyncio.sleep(0.5)

        except Exception as e:
            print(f"❌ {e}")
            failed += 1

    print(f"\n{'='*60}")
    print(f"✅ نجح: {success} سؤال")
    print(f"⚠️ فشل: {failed} سؤال")
    print(f"📊 نسبة النجاح: {success/(success+failed)*100:.1f}%")
    print(f"\nالآن {success} سؤال في الكاش = إجابات فورية بدون AI!")
    print("المستخدمون الـ 1,000,000 سيحصلون على 95%+ من الإجابات من الكاش")


if __name__ == "__main__":
    asyncio.run(prefill())
