def populate():
    conn = get_conn()
    cursor = conn.cursor()
    
    # 1. إنشاء جدول الفهارس النصية FTS5 للكتب
    cursor.execute("""
    CREATE VIRTUAL TABLE IF NOT EXISTS books_fts USING fts5(
        title_ar, content, category, author_ar,
        content='islamic_books', content_rowid='id',
        tokenize='unicode61 remove_diacritics 2'
    );
    """)
    
    # Triggers لمزامنة FTS تلقائياً
    cursor.execute("""
    CREATE TRIGGER IF NOT EXISTS books_ai AFTER INSERT ON islamic_books BEGIN
        INSERT INTO books_fts(rowid, title_ar, content, category, author_ar)
        VALUES (new.id, new.title_ar, new.content, new.category, new.author_ar);
    END;
    """)

    cursor.execute("""
    CREATE TRIGGER IF NOT EXISTS books_ad AFTER DELETE ON islamic_books BEGIN
        INSERT INTO books_fts(books_fts, rowid, title_ar, content, category, author_ar)
        VALUES ('delete', old.id, old.title_ar, old.content, old.category, old.author_ar);
    END;
    """)

    # 2. إدخال وتحديث البيانات
    inserted = 0
    updated = 0
    for entry in KNOWLEDGE_ENTRIES:
        existing = cursor.execute("SELECT id FROM islamic_books WHERE book_id=?", (entry["book_id"],)).fetchone()
        if existing:
            cursor.execute("""
                UPDATE islamic_books
                SET title_ar=?, category=?, author_ar=?, summary=?, content=?
                WHERE book_id=?
            """, (entry["title_ar"], entry["category"], entry["author_ar"], entry.get("summary", ""), entry["content"], entry["book_id"]))
            # تحديث FTS
            cursor.execute("DELETE FROM books_fts WHERE rowid=?", (existing["id"],))
            cursor.execute("INSERT INTO books_fts(rowid, title_ar, content, category, author_ar) VALUES (?, ?, ?, ?, ?)",
                           (existing["id"], entry["title_ar"], entry["content"], entry["category"], entry["author_ar"]))
            updated += 1
        else:
            cursor.execute("""
                INSERT INTO islamic_books (book_id, title_ar, category, author_ar, summary, content, lang)
                VALUES (?, ?, ?, ?, ?, ?, 'ar')
            """, (entry["book_id"], entry["title_ar"], entry["category"], entry["author_ar"], entry.get("summary", ""), entry["content"]))
            rowid = cursor.lastrowid
            cursor.execute("INSERT INTO books_fts(rowid, title_ar, content, category, author_ar) VALUES (?, ?, ?, ?, ?)",
                           (rowid, entry["title_ar"], entry["content"], entry["category"], entry["author_ar"]))
            inserted += 1

    conn.commit()
    total = cursor.execute("SELECT COUNT(*) FROM islamic_books").fetchone()[0]
    fts_total = cursor.execute("SELECT COUNT(*) FROM books_fts").fetchone()[0]
    conn.close()
    
    print(f"✅ تم بنجاح تغذية الموسوعة الإسلامية!")
    print(f"   - مدخلات جديدة: {inserted}")
    print(f"   - مدخلات تم تحديثها: {updated}")
    print(f"   - إجمالي الكتب والمراجع المفهرسة في DB: {total}")
    print(f"   - إجمالي الفهارس السريعة FTS5: {fts_total}")

if __name__ == "__main__":
    populate()
